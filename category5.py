solution = {}

def ao_star(node):
    if len(graph[node]) == 0:
        return h[node]

    min_cost = 9999
    best = None

    for option in graph[node]:
        cost = 0

        for child, value in option:
            cost += value + ao_star(child)

        if cost < min_cost:
            min_cost = cost
            best = option

    h[node] = min_cost
    solution[node] = best

    return min_cost

